/** Maps the English UI string to a translation key so chrome can be swapped automatically. */
export const ENGLISH_TO_KEY: Record<string, TranslationKey> = {}
for (const [key, value] of Object.entries(en) as [TranslationKey, string][]) {
  if (!value.includes('{')) {
    ENGLISH_TO_KEY[value] = key
  }
}

export function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template
  return Object.entries(vars).reduce(
    (text, [key, value]) => text.replaceAll(`{${key}}`, String(value)),
    template,
  )
}
